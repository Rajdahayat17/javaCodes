public class mergeOverlapping {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        System.out.println("Enter n");
        int n = sc.nextInt();
        System.out.println("Enter k");
        int k = sc.nextInt();
        System.out.println("output " + (n-k));
    }
}
